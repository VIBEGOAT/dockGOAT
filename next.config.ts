import type { NextConfig } from 'next';

const nextConfig: NextConfig = {
  // AutoDock Vina runs as multithreaded WebAssembly, which needs SharedArrayBuffer.
  // Browsers only expose it on cross-origin isolated pages, so every route is
  // served with COOP/COEP. External data (RCSB, PubChem, AlphaFold) is fetched
  // with CORS, which require-corp permits.
  async headers() {
    return [
      {
        source: '/:path*',
        headers: [
          { key: 'Cross-Origin-Opener-Policy', value: 'same-origin' },
          { key: 'Cross-Origin-Embedder-Policy', value: 'require-corp' },
          { key: 'Cross-Origin-Resource-Policy', value: 'same-origin' },
          { key: 'X-Content-Type-Options', value: 'nosniff' },
          { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
        ],
      },
      {
        source: '/vina/:file*',
        headers: [{ key: 'Cache-Control', value: 'public, max-age=3600, stale-while-revalidate=86400' }],
      },
      {
        source: '/rdkit/:file*',
        headers: [{ key: 'Cache-Control', value: 'public, max-age=3600, stale-while-revalidate=86400' }],
      },
    ];
  },
};

export default nextConfig;
